    function decodeMap(bytes, mapStart, width, height) {
        const len = bytes.length;
        const grid = new TileGrid(width, height);
        const total = width * height;
        let i = 0, tilecount = 0;
        const getByte = (idx) => {
            const off = mapStart + idx;
            if (off < 0 || off >= len) throw new RangeError('RLE read out of bounds at byte ' + idx);
            return bytes[off];
        };
        while (tilecount < total) {
            const first = getByte(i);
            if (first >= 0x3B && first <= 0x3E) {
                const x = tilecount % width, y = (tilecount / width) | 0;
                grid.set(x, y, { fam: 0, fenceT: false, fenceL: false, id: first - 0x3A, health: null });
                tilecount++; i++;
            } else if (first === 0x3F) {
                const repeat = getByte(i + 1);
                for (let k = 0; k < repeat; k++) {
                    const x = tilecount % width, y = (tilecount / width) | 0;
                    grid.set(x, y, { fam: 6, fenceT: false, fenceL: false, id: 9, health: null });
                    tilecount++;
                }
                i += 2;
            } else {
                const id = getByte(i + 1);
                const fam = first & 0x3F;
                const fenceT = !!(first & 0x40);
                const fenceL = !!(first & 0x80);
                let health = null;
                let consumed = 2;
                if (id >= 0x47) {
                    health = getByte(i + 2);
                    consumed = 3;
                }
                const x = tilecount % width, y = (tilecount / width) | 0;
                grid.set(x, y, { fam, fenceT, fenceL, id, health });
                tilecount++; i += consumed;
            }
        }
        return { grid, mapEnd: mapStart + i, bytesConsumed: i };
    }

    function encodeMap(grid) {
        const { width, height } = grid;
        const bytes = [];
        let waterRun = 0;
        const flushWater = () => {
            while (waterRun >= 255) { bytes.push(0x3F, 0xFF); waterRun -= 255; }
            if (waterRun > 0) { bytes.push(0x3F, waterRun); waterRun = 0; }
        };
        for (let y = 0; y < height; y++) {
            for (let x = 0; x < width; x++) {
                const i = grid.index(x, y);
                const isBorder = x === 0 || y === 0 || x === width - 1 || y === height - 1;
                const fam = isBorder ? 15 : grid.fam[i];
                const fenceT = grid.fenceT[i], fenceL = grid.fenceL[i];
                const flag = fam | (fenceT ? 0x40 : 0) | (fenceL ? 0x80 : 0);
                const id = grid.id[i];

                if (flag === 6 && id === 9) { waterRun++; if (waterRun === 255) flushWater(); continue; }
                flushWater();

                if (flag === 0 && id >= 1 && id <= 4) {
                    bytes.push(0x3A + id);
                    continue;
                }
                bytes.push(flag, id);
                if (id >= 0x47) {
                    const h = grid.health[i];
                    bytes.push(h === -1 ? 0 : h);
                }
            }
        }
        flushWater();
        return Uint8Array.from(bytes);
    }

    
    
    
    
    
    
    function parseRecordTable(bytes, view) {
        const len = bytes.length;
        if (len < 0x14) throw new Error('File too small to contain a record table');
        const count = u32(view, 0x10, len);
        let off = 0x14;
        const records = [];
        for (let idx = 0; idx < count; idx++) {
            if (off + 4 > len) throw new Error('Record ' + idx + ': missing name length');
            const nameLen = u32(view, off, len);
            const nameStart = off + 4, nameEnd = nameStart + nameLen;
            if (nameEnd > len) throw new Error('Record ' + idx + ': truncated name');
            const fixedOffset = nameEnd; 
            const linkCountOffset = fixedOffset + 18;
            if (linkCountOffset + 4 > len) throw new Error('Record ' + idx + ': truncated');
            const linkCount = u32(view, linkCountOffset, len);
            const linksStart = linkCountOffset + 4;
            const recordEnd = linksStart + linkCount * 4;
            if (recordEnd > len) throw new Error('Record ' + idx + ': truncated links');
            const links = [];
            for (let k = 0; k < linkCount; k++) links.push(u32(view, linksStart + k * 4, len));
            records.push({
                index: idx,
                name: new TextDecoder('utf-8').decode(bytes.slice(nameStart, nameEnd)),
                nameOffset: off, nameLen, fixedOffset, linkCountOffset, links, recordEnd
            });
            off = recordEnd;
        }
        return { count, tableEnd: off, records, names: records.map((r) => r.name) };
    }

    
    function locateMapBlock(bytes, view, tableEnd, version) {
        const len = bytes.length;
        const offset1 = tableEnd + 0xF0;
        const someCount = u32(view, offset1, len);
        const offset8 = offset1 + 4 + 8 * someCount;
        const offset6 = offset1 + 4 + 6 * someCount;

        const inRange = (off) => {
            if (off + 8 > len) return false;
            const w = u32(view, off, len), h = u32(view, off + 4, len);
            return w > 0 && w < 5000 && h > 0 && h < 5000;
        };

        const versionStride = version >= 12 ? 8 : 6;
        const versionOffset = versionStride === 8 ? offset8 : offset6;

        const rangeOffset8Ok = inRange(offset8);
        const rangeOffset6Ok = inRange(offset6);
        const rangePick = rangeOffset8Ok ? offset8 : (rangeOffset6Ok ? offset6 : null);

        if (rangePick === null || rangePick !== versionOffset || !inRange(versionOffset)) {
            throw new Error(
                'Map block location disagreement (version=' + version + '): ' +
                'version rule picked ' + (versionStride === 8 ? '8x' : '6x') +
                ' stride but the W/H range check picked ' +
                (rangeOffset8Ok ? '8x' : (rangeOffset6Ok ? '6x' : 'neither')) +
                '. Refusing to guess — unknown save format.'
            );
        }

        const width = u32(view, versionOffset, len);
        const height = u32(view, versionOffset + 4, len);
        const mapStart = versionOffset + 8;
        return { offset1, someCount, stride: versionStride, blockOffset: versionOffset, width, height, mapStart };
    }

    
    
    
    function parseBuried(bytes, view, mapEnd, width) {
        const len = bytes.length;
        const count = u32(view, mapEnd, len);
        const items = [];
        for (let i = 0; i < count; i++) {
            const entryOff = mapEnd + 4 + i * 8;
            const cell = u32(view, entryOff, len);
            const itemIndex = u32(view, entryOff + 4, len);
            items.push({
                itemIndex,
                x: (cell % width) * 32,
                y: Math.floor(cell / width) * 32 + 32
            });
        }
        return { items, buriedEnd: mapEnd + 4 + count * 8 };
    }

    function encodeBuried(items, width) {
        const buf = new Uint8Array(4 + items.length * 8);
        const view = new DataView(buf.buffer);
        writeU32(view, 0, items.length);
        for (let i = 0; i < items.length; i++) {
            const it = items[i];
            const cell = ((Math.floor(it.y / 32) - 1) * width) + Math.floor(it.x / 32);
            writeU32(view, 4 + i * 8, cell >>> 0);
            writeU32(view, 4 + i * 8 + 4, it.itemIndex);
        }
        return buf;
    }

    
    
    
    
    

    
