    function hutchStrings(bytes, view, tail, ownerFlag) {
        const len = bytes.length;
        let q = tail + 4 + (ownerFlag ? GENOME_LEN : 0);
        const out = [];
        for (let k = 0; k < LOC_HUTCH_STRINGS; k++) {
            if (q + 4 > len) return null;
            const n = u32(view, q, len);
            if (n > 255 || q + 4 + n > len) return null;
            out.push(new TextDecoder('utf-8').decode(bytes.slice(q + 4, q + 4 + n)));
            q += 4 + n;
        }
        return out;
    }

    
    function locationTailLength(bytes, view, index, tail) {
        const len = bytes.length;
        if (index === null || index === undefined || tail + 4 > len) return null;
        if (Object.prototype.hasOwnProperty.call(LOC_TAIL_FIXED, index)) return LOC_TAIL_FIXED[index];
        const owner = u32(view, tail, len);
        if (index === LOC_HUTCH_INDEX) {
            let q = tail + 4 + (owner ? GENOME_LEN : 0);
            for (let k = 0; k < LOC_HUTCH_STRINGS; k++) {
                if (q + 4 > len) return null;
                const n = u32(view, q, len);
                if (n > 255) return null;
                q += 4 + n;
            }
            return q + LOC_HUTCH_TRAILER - tail;
        }
        if (LOC_STABLE_INDICES.has(index)) {
            let n = 4 + (owner ? 2 * GENOME_LEN : 0) + LOC_STABLE_EXTRA;
            if (owner && tail + LOST_HORSE_FLAG_OFFSET + 4 <= len
                && u32(view, tail + LOST_HORSE_FLAG_OFFSET, len) === 1) n += LOST_HORSE_EXTRA;
            return n;
        }
        if (!Object.prototype.hasOwnProperty.call(LOC_TAIL_EXTRA, index)) return null;
        return 4 + (owner ? GENOME_LEN : 0) + LOC_TAIL_EXTRA[index];
    }

    
    function parseLocationRecord(bytes, view, i, HDR, index, tailEnd) {
        const len = bytes.length;
        const L = u32(view, i, len);
        const name = new TextDecoder('utf-8').decode(bytes.slice(i + 4, i + 4 + L));
        const crowdOff = i + 4 + L;
        const crowd = u32(view, crowdOff, len);

        
        
        const horses = [];
        const horseBlocks = [];                
        let ho = 0;
        for (let k = 0; k < crowd; k++) {
            const g = i + 8 + L + ho;
            horses.push(g);
            ho += GENOME_LEN;
            ho += 39 + u32(view, i + 8 + L + ho + 31, len);
            ho += 4 + u32(view, i + 8 + L + ho, len) * 8;
            ho += 4 + u32(view, i + 8 + L + ho, len) * 4 + 8;
            horseBlocks.push({ genomeOff: g, end: i + 8 + L + ho, length: i + 8 + L + ho - g });
        }

        const p = i + 8 + L + ho;              
        const sentinel = u32(view, p, len);    
        const interiorCount = u32(view, p + 4, len);

        const interior = [];
        let il = 0;
        for (let k = 0; k < interiorCount; k++) {
            const rec = p + 8 + il;
            interior.push(rec);
            if (u32(view, rec + 8, len)) il += 0xF0;
            il += HDR + 8;
        }

        const xoff = p + 8 + il;
        const tail = xoff + 8;

        const out = {
            index: (index === undefined ? null : index),
            nameOffset: i, name, nameLength: L,
            crowdOffset: crowdOff, crowd, horses, horseBlocks,
            crowdEnd: p, sentinel, interiorCount, interior,
            xoff, yoff: xoff + 4, x: f32(view, xoff, len), y: f32(view, xoff + 4, len),
            tailStart: tail, tailEnd: (tailEnd === undefined ? null : tailEnd),
            ownerFlag: (tail + 4 <= len) ? u32(view, tail, len) : null,
            ownerGenome: null, championGenome: null, lostHorse: null, bookies: [],
            strings: null, fields: {}
        };

        if (out.ownerFlag === 1 && isGenome(bytes, tail + 4)) {
            out.ownerGenome = tail + 4;
            if (isGenome(bytes, tail + 4 + GENOME_LEN)) out.championGenome = tail + 4 + GENOME_LEN;
        }
        if (tail + LOST_HORSE_FLAG_OFFSET + 4 <= len
            && u32(view, tail + LOST_HORSE_FLAG_OFFSET, len) === 1
            && isGenome(bytes, tail + LOST_HORSE_OFFSET)) {
            out.lostHorse = tail + LOST_HORSE_OFFSET;
        }
        const cand = [];
        for (let k = 0; k < RACE_OFFICIAL_COUNT; k++) cand.push(tail + BOOKIE_TAIL_OFFSET + RACE_OFFICIAL_STRIDE * k);
        if (cand.every((c) => isGenome(bytes, c))) out.bookies = cand;

        if (out.index === LOC_HUTCH_INDEX) out.strings = hutchStrings(bytes, view, tail, out.ownerFlag);
        if (out.index === 18 && tail + 248 <= len) out.fields.carsGenerated = u32(view, tail + 244, len);
        if (out.index === 31 && tail + VAT_COUNT_OFFSET + 4 <= len) out.fields.vatEntryCount = u32(view, tail + VAT_COUNT_OFFSET, len);

        if (out.tailEnd === null) {
            const tl = locationTailLength(bytes, view, out.index, tail);
            out.tailEnd = (tl === null) ? null : tail + tl;
        }
        return out;
    }

    
    function looksLikeLocationRecord(bytes, view, o) {
        const len = bytes.length;
        if (o + 8 > len) return false;
        const n = u32(view, o, len);
        if (!(n > 0 && n <= 255) || o + 8 + n > len) return false;
        for (let k = o + 4; k < o + 4 + n; k++) {
            const c = bytes[k];
            if (c < 0x20 || c >= 0x7f) return false;
        }
        return u32(view, o + 4 + n, len) <= 255;   
    }

    
    function walkLocations(bytes, view, worldItemEndOffset, HDR) {
        const len = bytes.length;
        const records = [];
        const slots = [];
        let o = worldItemEndOffset + LOC_BLOCK_PADDING;
        try {
            for (let idx = 0; idx <= LOC_MAX_INDEX; idx++) {
                if (o + 4 > len) return { records, slots, slotCount: idx, unknownOffset: null, error: 'ran off the end at index ' + idx };
                const present = u32(view, o, len);
                if (present > 1) {
                    if (!looksLikeLocationRecord(bytes, view, o)) {
                        return {
                            records, slots, slotCount: idx, unknownOffset: null,
                            error: 'desynchronised before index ' + idx + ': dword ' + present + ' at 0x' +
                                o.toString(16) + ' is neither a present flag nor a name length'
                        };
                    }
                    return { records, slots, slotCount: idx, unknownOffset: o, error: null };
                }
                slots[idx] = o;
                o += 4;
                if (present === 0) continue;
                const L = u32(view, o, len);
                
                
                
                if (L > 255) {
                    return { records, slots, slotCount: idx + 1, unknownOffset: null, error: 'bad nameLen ' + L + ' at index ' + idx };
                }
                const rec = parseLocationRecord(bytes, view, o, HDR, idx);
                if (rec.tailEnd === null) {
                    return { records, slots, slotCount: idx + 1, unknownOffset: null, error: 'no tail length for index ' + idx + ' (' + rec.name + ')' };
                }
                records.push(rec);
                o = rec.tailEnd;
            }
        } catch (e) {
            return { records, slots, slotCount: slots.length, unknownOffset: null, error: 'location walk failed: ' + e.message };
        }
        return { records, slots, slotCount: LOC_MAX_INDEX + 1, unknownOffset: o, error: 'ran past index ' + LOC_MAX_INDEX };
    }

    
    function readLocations(bytes, view, worldItemEndOffset, HDR) {
        const len = bytes.length;
        const walk = walkLocations(bytes, view, worldItemEndOffset, HDR);
        if (!walk.error) {
            const records = walk.records.slice();
            if (walk.unknownOffset !== null) {
                records.push(parseLocationRecord(bytes, view, walk.unknownOffset, HDR, null, len));
            }
            return {
                locations: records, slots: walk.slots, slotCount: walk.slotCount,
                unknownOffset: walk.unknownOffset, walkOk: true, walkError: null
            };
        }
        const raw = scanLocs(bytes, view, worldItemEndOffset);
        const records = raw.map((l, k) => {
            const nextStart = (k + 1 < raw.length) ? raw[k + 1].nameOffset : len;
            return parseLocationRecord(bytes, view, l.nameOffset, HDR, null, nextStart);
        });
        return {
            locations: records, slots: walk.slots, slotCount: walk.slotCount,
            unknownOffset: null, walkOk: false, walkError: walk.error
        };
    }

    
    function pairLocationMarkers(locations, markerList) {
        const named = locations.filter((l) => l.name !== 'unknown');
        if (named.length && named.every((l) => l.index !== null)) {
            const byIndex = new Map(markerList.map((m) => [m.index, m]));
            if (!named.every((l) => byIndex.has(l.index))) return false;
            for (const l of named) l.marker = byIndex.get(l.index);
            return true;
        }
        const sorted = markerList.slice().sort((a, b) => a.index - b.index);
        if (sorted.length !== named.length) return false;
        named.forEach((l, k) => { l.marker = sorted[k]; l.index = sorted[k].index; });
        return true;
    }

    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    function scanLocs(bytes, view, startOffset) {
        const n = bytes.length;
        const out = [];
        let i = startOffset;
        while (i <= n - 8) {
            const L = u32(view, i, n);
            if (!(L > 3 && L <= 255 && i + 8 + L <= n)) { i++; continue; }
            const crowd = u32(view, i + 4 + L, n);
            if (crowd > 255) { i++; continue; }
            let printable = true;
            for (let k = i + 4; k < i + 4 + L; k++) {
                const c = bytes[k];
                if (c < 0x20 || c >= 0x7f) { printable = false; break; }
            }
            if (!printable) { i++; continue; }

            let ho = 0, bail = false;
            const horses = [];
            for (let idx = 0; idx < crowd; idx++) {
                horses.push(i + 8 + L + ho);
                ho += 0xF0;
                if (i + 8 + L + ho + 40 > n) { bail = true; break; }
                let vl = u32(view, i + 8 + L + ho + 31, n);
                if (vl > 255) vl = 0;
                ho += 39 + vl;
                if (i + 8 + L + ho + 8 > n) { bail = true; break; }
                let ic = u32(view, i + 8 + L + ho, n);
                if (ic > 10) ic = 0;
                ho += 4 + ic * 8;
                if (i + 8 + L + ho + 8 > n) { bail = true; break; }
                const lx = u32(view, i + 8 + L + ho, n);
                ho += 4 + lx * 4 + 8;
            }
            if (bail) { i++; continue; }

            out.push({
                nameOffset: i,
                name: new TextDecoder('utf-8').decode(bytes.slice(i + 4, i + 4 + L)),
                crowd, horses
            });
            i += 4 + L;
        }
        return out;
    }

    
    
    
    
    
    
    
    function findVariableStrings(bytes, view, startPos, locationList) {
        const len = bytes.length;
        const locations = [];
        let locationIndex = 0;
        let stillFarm = true;
        const printableRegex = /^[\p{L}\p{N}\p{P}\p{Z}\p{S}]+$/u;

        for (let i = startPos; i <= len - 4; i++) {
            const length = u32(view, i, len);
            const length2 = (i + 8 + length) <= len ? u32(view, i + 4 + length, len) : -1;
            if (length2 > 255 || length2 < 0) continue;
            if (!(length > 3 && (i + 4 + length) <= len)) continue;

            let decodedString;
            try {
                const stringBuffer = bytes.slice(i + 4, i + 4 + length);
                decodedString = new TextDecoder('utf-8').decode(stringBuffer);
            } catch (e) { continue; }
            if (!printableRegex.test(decodedString)) continue;
            if (decodedString === 'unknown') continue;
            if (decodedString === 'Race Track') stillFarm = false;

            const isFarm = (locations.length >= 2 && stillFarm);
            let horseOffset = 0;
            let bail = false;
            for (let idx = 0; idx < length2; idx++) {
                horseOffset += 0xF0;
                if ((i + 8 + length + horseOffset + 31 + 3) > len) { bail = true; break; }
                let voiceStrLen = u32(view, i + 8 + length + horseOffset + 31, len);
                if (voiceStrLen > 255 || voiceStrLen < 0) voiceStrLen = 0;
                horseOffset += 39 + voiceStrLen;
                let itemcount = u32(view, i + 8 + length + horseOffset, len);
                if (itemcount > 10 || itemcount < 0) itemcount = 0;
                horseOffset += 4 + (itemcount * 8);
                const lengthX = u32(view, i + 8 + length + horseOffset, len);
                horseOffset += 4 + (lengthX * 4) + 8;
            }
            if (bail) continue;
            if ((i + 12 + length + horseOffset + 3) > len) continue;

            const length3 = u32(view, i + 12 + length + horseOffset, len);
            if (length3 > 255) continue;
            let itemlength3 = 0;
            for (let idx3 = 0; idx3 < length3; idx3++) {
                const hasDna = u32(view, i + 12 + length + horseOffset + itemlength3 + 12, len);
                if (hasDna) itemlength3 += 0xF0;
                itemlength3 += 49;
            }
            const xoff = i + 16 + length + itemlength3 + horseOffset;
            const yoff = xoff + 4;
            const x = f32(view, xoff, len);
            const y = f32(view, yoff, len);
            if (x < 10 || y < 10) continue;

            const locItem = locationList[locationIndex];
            if (!locItem) continue;
            locationIndex++;
            locations.push({
                index: locItem.index, offset: i, length, value: decodedString, isFarm, crowd: length2,
                xoff, yoff, xoff2: locItem.offX, yoff2: locItem.offY, x, y
            });
        }
        return locations;
    }

    
    
    
    
    function isGenome(bytes, g) {
        if (g < 0 || g + GENOME_LEN > bytes.length) return false;
        for (let j = 0; j < GENOME_LEN; j++) if (!CODESET.has(bytes[g + j])) return false;
        return true;
    }

    
    function raceOfficials(bytes, crowdLocs) {
        const rt = crowdLocs.find((l) => l.name === 'Race Track');
        if (!rt) return [];
        if (rt.bookies && rt.bookies.length === RACE_OFFICIAL_COUNT) return rt.bookies.slice();
        const n = bytes.length;
        const base = rt.horses && rt.horses.length ? rt.horses[rt.horses.length - 1] + GENOME_LEN + DETAIL_GAP : rt.nameOffset;
        const searchEnd = Math.min(base + RACE_OFFICIAL_SEARCH, n - GENOME_LEN);
        for (let g = base; g < searchEnd; g++) {
            if (!CODESET.has(bytes[g])) continue;
            let allOk = true;
            const run = [];
            for (let k = 0; k < RACE_OFFICIAL_COUNT; k++) {
                const x = g + k * RACE_OFFICIAL_STRIDE;
                if (!isGenome(bytes, x)) { allOk = false; break; }
                run.push(x);
            }
            if (allOk) return run;
        }
        return [];
    }

    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
