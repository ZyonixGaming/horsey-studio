    function walkStabledBlocks(bytes, count) {
        const spans = [];
        let off = 0;
        for (let k = 0; k < count; k++) {
            if (off >= bytes.length) {
                throw new Error('Crowd blob holds only ' + k + ' of ' + count + ' horse blocks.');
            }
            const length = measureStabledHorseRecord(bytes.subarray(off));
            spans.push({ start: off, length });
            off += length;
        }
        if (off !== bytes.length) {
            throw new Error('Crowd blob is ' + bytes.length + ' bytes but its ' + count +
                ' horse blocks measure ' + off + '.');
        }
        return spans;
    }

    
    function retargetStabledBlocks(bytes, count, recordIndexes) {
        const out = bytes.slice();
        const view = new DataView(out.buffer, out.byteOffset, out.byteLength);
        walkStabledBlocks(out, count).forEach((span, k) => {
            const ri = recordIndexes[k];
            if (ri === undefined || ri === null) return;
            writeI32(view, span.start + GENOME_LEN + DETAIL_GAP, ri);
        });
        return out;
    }

    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    

    
