    function clampView() {
        if (!doc) return;
        const { w, h } = getCanvasSize();
        const worldW = doc.grid.width * TILE_PX, worldH = doc.grid.height * TILE_PX;
        const viewW = w / view.zoom, viewH = h / view.zoom;
        view.offsetX = Math.min(Math.max(0, view.offsetX), Math.max(0, worldW - viewW));
        view.offsetY = Math.min(Math.max(0, view.offsetY), Math.max(0, worldH - viewH));
    }

    function renderViewport() {
        const canvas = document.getElementById('viewportCanvas');
        const ctx = canvas.getContext('2d');
        ctx.imageSmoothingEnabled = false;
        ctx.fillStyle = '#0c0c14';
        ctx.fillRect(0, 0, canvas.width, canvas.height);
        if (!doc || !atlas.ready) return;

        const { zoom, offsetX, offsetY } = view;
        const grid = doc.grid;
        const terrain = atlas.terrain;
        const firstTileX = Math.max(0, Math.floor(offsetX / TILE_PX));
        const firstTileY = Math.max(0, Math.floor(offsetY / TILE_PX));
        const lastTileX = Math.min(grid.width - 1, Math.ceil((offsetX + canvas.width / zoom) / TILE_PX));
        const lastTileY = Math.min(grid.height - 1, Math.ceil((offsetY + canvas.height / zoom) / TILE_PX));

        ctx.save();
        ctx.scale(zoom, zoom);
        ctx.translate(-offsetX, -offsetY);

        for (let y = firstTileY; y <= lastTileY; y++) {
            for (let x = firstTileX; x <= lastTileX; x++) {
                const t = grid.get(x, y);
                const rect = terrainSpriteRect(t.id, t.health);
                ctx.drawImage(terrain.img, rect.sx, rect.sy, rect.sw, rect.sh, x * TILE_PX, y * TILE_PX, TILE_PX, TILE_PX);
                if (overlays.health && t.id >= 71) {
                    const fam = SaveFile.VEGETATION[t.id];
                    const pct = fam ? (t.health ?? fam.maxHealth) / fam.maxHealth : 1;
                    ctx.fillStyle = `rgba(${255 - Math.round(pct * 255)}, ${Math.round(pct * 200)}, 40, 0.45)`;
                    ctx.fillRect(x * TILE_PX, y * TILE_PX, TILE_PX, TILE_PX);
                }
                if (overlays.debug) {
                    ctx.strokeStyle = 'rgba(255,255,255,0.25)';
                    ctx.strokeRect(x * TILE_PX + 0.5, y * TILE_PX + 0.5, TILE_PX - 1, TILE_PX - 1);
                }
            }
        }
        const fenceSprite = terrain.sprites['FenceIcon'], fenceVSprite = terrain.sprites['FenceIconNotNeeded'];
        for (let y = firstTileY; y <= lastTileY; y++) {
            for (let x = firstTileX; x <= lastTileX; x++) {
                const t = grid.get(x, y);
                if (t.fenceT && fenceSprite) ctx.drawImage(terrain.img, fenceSprite.x, fenceSprite.y, fenceSprite.w, fenceSprite.h, x * TILE_PX, y * TILE_PX - fenceSprite.hy, fenceSprite.w, fenceSprite.h);
                if (t.fenceL && fenceVSprite) ctx.drawImage(terrain.img, fenceVSprite.x, fenceVSprite.y, fenceVSprite.w, fenceVSprite.h, x * TILE_PX - fenceVSprite.hx, y * TILE_PX, fenceVSprite.w, fenceVSprite.h);
            }
        }
        if (overlays.debug) {
            ctx.fillStyle = '#fff'; ctx.font = '6px monospace';
            for (let y = firstTileY; y <= lastTileY; y++) for (let x = firstTileX; x <= lastTileX; x++) {
                const t = grid.get(x, y);
                ctx.fillText(t.fam + (t.fenceT ? 'T' : '') + (t.fenceL ? 'L' : ''), x * TILE_PX + 1, y * TILE_PX + 7);
            }
        }

        const viewRect = { x0: offsetX, y0: offsetY, x1: offsetX + canvas.width / zoom, y1: offsetY + canvas.height / zoom };
        drawOverlayMarkers(ctx, viewRect);
        drawMapSelection(ctx);
        drawDragPreview(ctx);
        ctx.restore();
        renderMinimapViewbox();
    }

    function drawDiamondMarker(ctx, wx, wy) {
        const s = 5;
        ctx.beginPath();
        ctx.moveTo(wx, wy - s); ctx.lineTo(wx + s, wy); ctx.lineTo(wx, wy + s); ctx.lineTo(wx - s, wy);
        ctx.closePath(); ctx.fill();
        ctx.strokeStyle = 'rgba(0,0,0,0.6)'; ctx.lineWidth = 1 / view.zoom; ctx.stroke();
    }

    function drawOverlayMarkers(ctx, viewRect) {
        if (!doc) return;
        const locs = atlas.locs;
        const inView = (x, y) => x >= viewRect.x0 - TILE_PX && x <= viewRect.x1 + TILE_PX && y >= viewRect.y0 - TILE_PX && y <= viewRect.y1 + TILE_PX;
        const labels = [];

        if (overlays.locations && locs) {
            for (const loc of mapSpaceMarkers()) {
                if (loc.value === 'Truck') continue;
                if (!inView(loc.x, loc.y)) continue;
                const rect = locsSpriteRect(loc.index);
                ctx.drawImage(locs.img, rect.sx, rect.sy, rect.sw, rect.sh, loc.x - TILE_PX / 2, loc.y - TILE_PX / 2, TILE_PX, TILE_PX);
                labels.push({ x: loc.x, y: loc.y - TILE_PX / 2, text: loc.value });
            }
            const vial = doc.state.locationMarkers.find((l) => l.value === 'vial world');
            if (vial) {
                const vEdit = doc.locationEdits.get(vial.offset);
                const vx = vEdit ? vEdit.x : vial.x, vy = vEdit ? vEdit.y : vial.y;
                if (inView(vx, vy)) {
                    const rect = locsSpriteRect(vial.index);
                    ctx.drawImage(locs.img, rect.sx, rect.sy, rect.sw, rect.sh, vx, vy, TILE_PX, TILE_PX);
                    labels.push({ x: vx + TILE_PX / 2, y: vy, text: 'vial world' });
                }
            }
            const truck = doc.state.locationMarkers.find((l) => l.value === 'Truck');
            if (truck) {
                const edit = doc.locationEdits.get(truck.offset);
                const tx = edit ? edit.x : truck.x, ty = edit ? edit.y : truck.y;
                if (inView(tx, ty)) {
                    const rect = locsSpriteRect(truck.index);
                    ctx.drawImage(locs.img, rect.sx, rect.sy, rect.sw, rect.sh, tx - TILE_PX / 2, ty - TILE_PX / 2, TILE_PX, TILE_PX);
                    labels.push({ x: tx, y: ty - TILE_PX / 2, text: 'Truck' });
                }
            }
        }
        if (overlays.ground) {
            ctx.fillStyle = '#66d9ef';
            for (const g of activeItemsOfType(3)) {
                if (!inView(g.x, g.y)) continue;
                drawDiamondMarker(ctx, g.x, g.y);
                labels.push({ x: g.x, y: g.y - 6, text: (Items.ITEM_LIST[g.index] || {}).displayName || ('item ' + g.index) });
            }
        }
        if (overlays.holes) {
            ctx.fillStyle = '#5c3a1e';
            for (const h of activeItemsOfType(4)) if (inView(h.x, h.y)) drawDiamondMarker(ctx, h.x, h.y);
        }
        if (overlays.buried) {
            ctx.fillStyle = '#ffd966';
            for (const b of doc.buriedItems) {
                if (!inView(b.x, b.y)) continue;
                drawDiamondMarker(ctx, b.x, b.y);
                labels.push({ x: b.x, y: b.y - 6, text: (Items.ITEM_LIST[b.itemIndex] || {}).displayName || ('item ' + b.itemIndex) });
            }
        }
        if (overlays.horses) {
            for (const h of activeItemsOfType(0)) {
                if (!inView(h.x, h.y)) continue;
                ctx.fillStyle = horseMarkerColor(h);
                drawDiamondMarker(ctx, h.x, h.y);
                const name = horseName(h);
                if (name) labels.push({ x: h.x, y: h.y - 6, text: name });
            }
        }
        if (overlays.labels && view.zoom >= 0.75) {
            ctx.save();
            ctx.font = Math.max(1, 11 / view.zoom) + 'px monospace';
            ctx.textAlign = 'center';
            ctx.lineWidth = Math.max(1, 3 / view.zoom);
            ctx.strokeStyle = 'rgba(0,0,0,0.85)';
            ctx.fillStyle = '#fff';
            for (const l of labels) { ctx.strokeText(l.text, l.x, l.y - 3); ctx.fillText(l.text, l.x, l.y - 3); }
            ctx.restore();
        }
    }

