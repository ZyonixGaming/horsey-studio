    function ringPositions(wx, wy, n) {
        if (n === 1) return [{ x: wx, y: wy }];
        const out = [];
        const radius = TILE_PX * (n <= 6 ? 1.5 : Math.max(2, Math.sqrt(n) * 0.8));
        for (let i = 0; i < n; i++) {
            const a = (2 * Math.PI * i) / n;
            out.push({ x: wx + radius * Math.cos(a), y: wy + radius * Math.sin(a) });
        }
        return out;
    }

