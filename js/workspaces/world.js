    function findFreeInteriorTile(startTx, startTy, width, height, occupied) {
        const minTx = 1, maxTx = Math.max(1, width - 2), minTy = 1, maxTy = Math.max(1, height - 2);
        const cx = Math.min(Math.max(startTx, minTx), maxTx), cy = Math.min(Math.max(startTy, minTy), maxTy);
        const key = (tx, ty) => tx + ',' + ty;
        if (!occupied.has(key(cx, cy))) return { tx: cx, ty: cy };
        const maxRadius = Math.max(maxTx - minTx, maxTy - minTy) + 1;
        for (let r = 1; r <= maxRadius; r++) {
            for (let dx = -r; dx <= r; dx++) for (let dy = -r; dy <= r; dy++) {
                if (Math.max(Math.abs(dx), Math.abs(dy)) !== r) continue;
                const tx = cx + dx, ty = cy + dy;
                if (tx < minTx || tx > maxTx || ty < minTy || ty > maxTy) continue;
                if (!occupied.has(key(tx, ty))) return { tx, ty };
            }
        }
        return { tx: cx, ty: cy };
    }

    async function applyResize() {
        const newW = parseInt(document.getElementById('resizeWidth').value, 10);
        const newH = parseInt(document.getElementById('resizeHeight').value, 10);
        if (!(newW > 0 && newW < 5000 && newH > 0 && newH < 5000)) { await Modal.alertModal('Dimensions out of range.'); return; }

        const oldGrid = doc.grid;
        const newGrid = new SaveFile.TileGrid(newW, newH);
        for (let y = 0; y < newH; y++) {
            for (let x = 0; x < newW; x++) {
                const isBorder = x === 0 || y === 0 || x === newW - 1 || y === newH - 1;
                if (x < oldGrid.width && y < oldGrid.height) {
                    const t = oldGrid.get(x, y);
                    newGrid.set(x, y, isBorder ? Object.assign({}, t, { fam: 15 }) : t);
                } else {
                    newGrid.set(x, y, { fam: isBorder ? 15 : 6, fenceT: false, fenceL: false, id: 9, health: null });
                }
            }
        }
        const oldW = doc.grid.width, oldH = doc.grid.height;
        const apply = (grid, delta) => { doc.grid = grid; doc.touchGrid(delta); doc._touched(); };
        apply(newGrid, +1);
        doc.history.push({ label: 'resize map', undo: () => apply(oldGrid, -1), redo: () => apply(newGrid, +1) });

        document.getElementById('resizeModal').classList.remove('show');
        renderMinimap();
        setZoom('fit');
        selection = null;
        renderInspector(); renderChoosers();
        scheduleRender();
        Toast.toast(`Resized ${oldW}x${oldH} → ${newW}x${newH}. Objects outside the new bounds were not relocated — check the Objects tab for anything now out of range.`, 'warn', 6000);
    }

    
    
    
