    function floodFill(startX, startY) {
        const grid = doc.grid;
        if (!grid.inBounds(startX, startY)) return;
        const target = grid.get(startX, startY);
        if (target.fam === palette.fam && target.id === palette.id) return;
        const stack = [[startX, startY]];
        const seen = new Uint8Array(grid.width * grid.height);
        const matches = (x, y) => { const t = grid.get(x, y); return t.fam === target.fam && t.id === target.id; };
        let guard = grid.width * grid.height;
        while (stack.length && guard-- > 0) {
            const [x, y] = stack.pop();
            if (!grid.inBounds(x, y)) continue;
            const idx = y * grid.width + x;
            if (seen[idx]) continue;
            seen[idx] = 1;
            if (!matches(x, y)) continue;
            setTileWithUndo(x, y, paletteToTile(x, y));
            stack.push([x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]);
        }
    }
    function drawLineTiles(x0, y0, x1, y1, size) {
        let dx = Math.abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
        let dy = -Math.abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
        let err = dx + dy, x = x0, y = y0;
        for (let guard = 0; guard < 100000; guard++) {
            paintAt(x, y, size);
            if (x === x1 && y === y1) break;
            const e2 = 2 * err;
            if (e2 >= dy) { err += dy; x += sx; }
            if (e2 <= dx) { err += dx; y += sy; }
        }
    }
