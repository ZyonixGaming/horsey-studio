    function computeAllowedSets(genomeA, genomeB) {
        const allowed = new Array(Genome.HELIX_COUNT);
        let valid = true;
        for (let h = 0; h < Genome.HELIX_COUNT; h++) {
            const len = Genome.HELIX_LENGTHS[h];
            allowed[h] = new Array(len);
            const strands = [
                (genomeA[h] && genomeA[h][0]) || '', (genomeA[h] && genomeA[h][1]) || '',
                (genomeB[h] && genomeB[h][0]) || '', (genomeB[h] && genomeB[h][1]) || ''
            ];
            for (let pos = 0; pos < len; pos++) {
                const set = new Set();
                for (const s of strands) { const ch = s[pos]; if (ch && 'ATCG'.includes(ch)) set.add(ch); }
                if (set.size === 0) valid = false;
                allowed[h][pos] = set;
            }
        }
        return { allowed, valid };
    }
    function buildRandomGenomeFromPools(allowed) {
        const genome = new Array(Genome.HELIX_COUNT);
        for (let h = 0; h < Genome.HELIX_COUNT; h++) {
            const len = Genome.HELIX_LENGTHS[h];
            let s1 = '', s2 = '';
            for (let pos = 0; pos < len; pos++) {
                const bases = Array.from(allowed[h][pos]);
                s1 += bases[Math.floor(Math.random() * bases.length)];
                s2 += bases[Math.floor(Math.random() * bases.length)];
            }
            genome[h] = [s1, s2];
        }
        return genome;
    }

    
    
    
    
    
    
    
    
    
