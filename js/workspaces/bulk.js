    async function init() {
        if (inited) return;
        inited = true;
        paneEl = document.querySelector('.workspace-pane[data-workspace="bulk"]');
        cacheEls();
        if (typeof AppBus !== 'undefined') AppBus.on('mapSelection:changed', () => { if (isPaneActive()) renderAll(); });
        try {
            const [genesXml, popXml] = await Promise.all([
                fetch('data/genes.xml').then((r) => { if (!r.ok) throw new Error('HTTP ' + r.status); return r.text(); }),
                fetch('data/pop.xml').then((r) => { if (!r.ok) throw new Error('HTTP ' + r.status); return r.text(); })
            ]);
            const genes = GeneData.parseGenesXml(genesXml);
            geneTable = GeneData.buildGeneById(genes);
            geneByDesc = GeneData.buildGeneByDesc(genes);
            popTable = PopData.parsePopXml(popXml);
            presetNames = [...popTable.keys()];
            params.replaceDna.popName = popTable.has('default') ? 'default' : (presetNames[0] || '');
            dataReady = true;
        } catch (e) {
            console.error('Bulk workspace: failed to load gene/pop data', e);
            Toast.toast('Bulk workspace: failed to load genome data: ' + e.message, 'bad', 0);
        }
        renderAll();
    }

    function onDocLoaded(newDoc) {
        doc = newDoc;
        target.oneLocation = false;
        target.locationIndex = 0;
        target.bookies = false; 
        target.inSelection = false;
        if (doc) doc.bus.on('doc:changed', onDocChanged);
        if (!inited) return;
        renderAll();
    }

    function onActivate() { if (inited) renderAll(); }

    return { init, onDocLoaded, onActivate };
